-- 4.1 Trigger Auto-Create Profile & Validasi Email Kampus Unsika
CREATE OR REPLACE FUNCTION public.handle_new_campus_user()
RETURNS TRIGGER 
SECURITY DEFINER
SET search_path = public, auth
LANGUAGE plpgsql
AS $$ DECLARE extracted_npm VARCHAR(50); extracted_name VARCHAR(150); BEGIN -- Validasi Domain Email Unsika IF NEW.email NOT LIKE '\%@unsika.ac.id' AND NEW.email NOT LIKE '\%@student.unsika.ac.id' THEN RAISE EXCEPTION 'Registrasi ditolak: Wajib menggunakan email resmi Unsika (@unsika.ac.id atau @student.unsika.ac.id)!'; END IF;    -- Ambil metadata atau siapkan fallback otomatis extracted_npm := COALESCE(NEW.raw_user_meta_data->>'npm', 'MHS-' \vert{}\vert{} SUBSTRING(NEW.id::text, 1, 8)); extracted_name := COALESCE(NEW.raw_user_meta_data->>'full_name', SPLIT_PART(NEW.email, '@', 1));    INSERT INTO public.profiles (id, email, npm, full_name, role, is_active, last_login) VALUES ( NEW.id, NEW.email, extracted_npm, extracted_name, COALESCE(NEW.raw_user_meta_data->>'role', 'mahasiswa'), true, NOW() ) ON CONFLICT (id) DO UPDATE SET email = EXCLUDED.email, last_login = NOW();    RETURN NEW; EXCEPTION WHEN OTHERS THEN -- Jika error selain masalah domain, catat warning agar tidak memblokir sistem IF SQLERRM LIKE 'Registrasi ditolak:\%' THEN RAISE EXCEPTION '\%', SQLERRM; END IF; RAISE WARNING 'Auto-create profile failed: \%', SQLERRM; RETURN NEW; END; $$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_new_campus_user();

-- 4.2 Trigger Proteksi Kolom `role` (Mencegah Mahasiswa Eskalasi Role via Inspect Element)
CREATE OR REPLACE FUNCTION public.protect_profile_roles()
RETURNS TRIGGER 
LANGUAGE plpgsql
AS $$ BEGIN IF NEW.role IS DISTINCT FROM OLD.role AND auth.role() = 'authenticated' THEN IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin') THEN RAISE EXCEPTION 'Akses ditolak: Anda tidak memiliki izin mengubah role akun!'; END IF; END IF; RETURN NEW; END; $$;

DROP TRIGGER IF EXISTS tr_protect_roles ON public.profiles;
CREATE TRIGGER tr_protect_roles
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW
  EXECUTE FUNCTION public.protect_profile_roles();

-- ============================================================================
-- 5. RPC FUNCTIONS (REMOTE PROCEDURE CALLS)
-- ============================================================================

-- 5.1 RPC Increment Views Materi (Aman dipanggil Mahasiswa tanpa buka akses UPDATE tabel)
CREATE OR REPLACE FUNCTION public.increment_material_views(target_material_id UUID)
RETURNS VOID 
SECURITY DEFINER
SET search_path = public
LANGUAGE plpgsql
AS $$ BEGIN UPDATE public.materials SET views_count = COALESCE(views_count, 0) + 1 WHERE id = target_material_id; END; $$;

GRANT EXECUTE ON FUNCTION public.increment_material_views(UUID) TO authenticated;

-- 5.2 RPC Ubah Role Pengguna (Khusus Admin dari Dashboard)
CREATE OR REPLACE FUNCTION public.set_user_role(target_user_id UUID, new_role VARCHAR)
RETURNS VOID
SECURITY DEFINER
SET search_path = public
LANGUAGE plpgsql
AS $$ BEGIN IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin') THEN RAISE EXCEPTION 'Akses ditolak: Hanya Admin yang berhak mengubah role.'; END IF;    UPDATE public.profiles SET role = new_role WHERE id = target_user_id; END; $$;

GRANT EXECUTE ON FUNCTION public.set_user_role(UUID, VARCHAR) TO authenticated;

-- 5.3 RPC Hapus User Permanen dari Auth & Profiles (Khusus Admin)
CREATE OR REPLACE FUNCTION public.delete_user_by_admin(target_user_id UUID)
RETURNS VOID
SECURITY DEFINER
SET search_path = public, auth
LANGUAGE plpgsql
AS $$ BEGIN IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin') THEN RAISE EXCEPTION 'Akses ditolak: Hanya Admin yang berhak menghapus pengguna.'; END IF;    DELETE FROM auth.users WHERE id = target_user_id; END; $$;

GRANT EXECUTE ON FUNCTION public.delete_user_by_admin(UUID) TO authenticated;