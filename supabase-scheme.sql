CREATE POLICY "Authenticated users read materials" ON public.materials
  FOR SELECT USING (auth.role() = 'authenticated');

DROP POLICY IF EXISTS "Admin full access materials" ON public.materials;
CREATE POLICY "Admin full access materials" ON public.materials
  FOR ALL USING (
    EXISTS (
      SELECT 1 FROM public.profiles
      WHERE profiles.id = auth.uid() AND profiles.role = 'admin'
    )
  );

-- 3.4 Policies untuk `reading_histories`
